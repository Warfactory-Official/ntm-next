package com.hbm.transform;

import java.util.HashSet;
import java.util.List;
import java.util.Set;
import net.fabricmc.loader.api.FabricLoader;
import org.objectweb.asm.tree.ClassNode;
import org.spongepowered.asm.mixin.extensibility.IMixinConfigPlugin;
import org.spongepowered.asm.mixin.extensibility.IMixinInfo;

public class OptionalModMixinPlugin implements IMixinConfigPlugin {
    private static final Set<String> ABSENT;

    static {
        var absent = new HashSet<String>();
        OptionalMixinTargets.absent(id -> FabricLoader.getInstance().isModLoaded(id), absent);
        ABSENT = Set.copyOf(absent);
    }

    @Override
    public boolean shouldApplyMixin(String target, String mixin) {
        return !ABSENT.contains(target);
    }

    @Override
    public void onLoad(String mixinPackage) {}

    @Override
    public String getRefMapperConfig() {
        return null;
    }

    @Override
    public void acceptTargets(Set<String> mine, Set<String> other) {}

    @Override
    public List<String> getMixins() {
        return null;
    }

    @Override
    public void preApply(String target, ClassNode node, String mixin, IMixinInfo info) {}

    @Override
    public void postApply(String target, ClassNode node, String mixin, IMixinInfo info) {}
}
