package com.hbm.blocks.network;

import com.hbm.blockentity.network.PipeGaugeBlockEntity;
import com.hbm.blocks.TickingEntityBlock;
import com.hbm.interfaces.LookOverlay;
import java.util.Locale;
import net.minecraft.core.BlockPos;
import net.minecraft.core.Direction;
import net.minecraft.network.chat.Component;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.item.context.BlockPlaceContext;
import net.minecraft.world.level.Level;
import net.minecraft.world.level.LevelReader;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.Mirror;
import net.minecraft.world.level.block.Rotation;
import net.minecraft.world.level.block.entity.BlockEntity;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.level.block.state.StateDefinition;
import net.minecraft.world.level.block.state.properties.BlockStateProperties;
import net.minecraft.world.level.block.state.properties.EnumProperty;
import org.jspecify.annotations.Nullable;

public class FluidDuctGaugeBlock extends FluidDuctBlock implements TickingEntityBlock {

    public static final EnumProperty<Direction> FACING = BlockStateProperties.FACING;

    public FluidDuctGaugeBlock(Properties props) {
        super(props);
        registerDefaultState(stateDefinition.any().setValue(FACING, Direction.NORTH));
    }

    @Override
    protected void createBlockStateDefinition(StateDefinition.Builder<Block, BlockState> builder) {
        builder.add(FACING);
    }

    @Override
    public @Nullable BlockState getStateForPlacement(BlockPlaceContext ctx) {
        return defaultBlockState().setValue(FACING, ctx.getNearestLookingDirection().getOpposite());
    }

    @Override
    protected BlockState rotate(BlockState state, Rotation rotation) {
        return state.setValue(FACING, rotation.rotate(state.getValue(FACING)));
    }

    @Override
    protected BlockState mirror(BlockState state, Mirror mirror) {
        return state.rotate(mirror.getRotation(state.getValue(FACING)));
    }

    @Override
    public @Nullable BlockEntity newBlockEntity(BlockPos pos, BlockState state) {
        return new PipeGaugeBlockEntity(pos, state);
    }

    public void restoreNode(ServerLevel level, BlockPos pos, BlockState state) {
        createNodes(level, pos, state);
    }

    @Override
    public void buildLookOverlay(Level level, BlockPos pos, LookOverlay info) {
        super.buildLookOverlay(level, pos, info);
        if (level.getBlockEntity(pos) instanceof PipeGaugeBlockEntity gauge) {
            info.row(
                    Component.translatable(
                            "unit.millibuckets_per_tick_spaced",
                            String.format(Locale.ROOT, "%,d", gauge.getTransferredThisTick())));
            info.row(
                    Component.translatable(
                            "unit.millibuckets_per_second_spaced",
                            String.format(Locale.ROOT, "%,d", gauge.getTransferredLastInterval())));
        }
    }

    @Override
    protected ItemStack getCloneItemStack(
            LevelReader level, BlockPos pos, BlockState state, boolean includeData) {
        return new ItemStack(this);
    }
}
