package com.hbm.blocks.machine;

import net.minecraft.core.Direction;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.state.BlockBehaviour;
import net.minecraft.world.level.block.state.BlockState;

public class CMTankBlock extends Block {
    public CMTankBlock(BlockBehaviour.Properties properties) {
        super(properties);
    }

    @Override
    protected boolean skipRendering(BlockState state, BlockState neighbour, Direction direction) {
        return neighbour.getBlock() instanceof CMTankBlock
                || super.skipRendering(state, neighbour, direction);
    }
}
