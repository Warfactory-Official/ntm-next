package com.hbm.fabric.mixin;

import com.hbm.items.tool.ItemDeadManDetonator;
import net.minecraft.server.level.ServerPlayer;
import net.minecraft.world.damagesource.DamageSource;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

@Mixin(ServerPlayer.class)
public abstract class MixinServerPlayer {

    @Inject(method = "die", at = @At("HEAD"))
    private void hbm$fireDeadManSwitches(DamageSource source, CallbackInfo ci) {
        ItemDeadManDetonator.onOwnerDeath((ServerPlayer) (Object) this);
    }
}
