package com.hbm.fabric.mixin;

import com.hbm.items.special.NuclearWasteItem;
import net.minecraft.world.entity.Entity;
import net.minecraft.world.entity.item.ItemEntity;
import net.minecraft.world.item.ItemStack;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

@Mixin(ItemEntity.class)
public abstract class MixinItemEntity {

    @Inject(method = "setItem", at = @At("TAIL"))
    private void hbm$wasteImmortal(ItemStack stack, CallbackInfo ci) {
        if (stack.getItem() instanceof NuclearWasteItem) {
            ItemEntity self = (ItemEntity) (Object) this;
            self.setUnlimitedLifetime();
            ((Entity) self).setInvulnerable(true);
        }
    }
}
