        double y = worldPosition.getY() + (travel * facing.getStepY()) % length + 0.5D;
        double z = worldPosition.getZ() + (travel * facing.getStepZ()) % length + 0.5D;
        float pitch =
                switch (facing) {
                    case NORTH, WEST -> 90F;
                    case SOUTH, EAST -> -90F;
                    case DOWN, UP -> 0F;
                };
        float yaw = facing.getAxis() == Direction.Axis.X ? 90F : 0F;
