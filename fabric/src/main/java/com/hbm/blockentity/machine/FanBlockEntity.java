    private int freeReach(Level level, BlockPos pos, Direction direction) {
        var cursor = new BlockPos.MutableBlockPos();
        for (int distance = 1; distance <= 10; distance++) {
            cursor.set(
                    pos.getX() + direction.getStepX() * distance,
                    pos.getY() + direction.getStepY() * distance,
                    pos.getZ() + direction.getStepZ() * distance);
            var state = level.getBlockState(cursor);
            var receiver = NtmContracts.BLOWABLE.at(level, cursor, state);
            if (receiver != null) {
                if (!level.isClientSide()) receiver.applyFan(level, cursor, direction, distance);
                return distance - 1;
            }
            if (state.canOcclude()
                    && state.isCollisionShapeFullBlock(level, cursor)
                    && !state.isSignalSource()) {
                return distance - 1;
            }
        }
        return 10;
    }

    private void moveEntities(Level level, BlockPos pos, Direction direction, int reach) {
        double x = pos.getX() + 0.5;
        double y = pos.getY() + 0.5;
        double z = pos.getZ() + 0.5;
        var bounds =
                new AABB(
                                x,
                                y,
                                z,
                                x + direction.getStepX() * reach,
                                y + direction.getStepY() * reach,
                                z + direction.getStepZ() * reach)
                        .inflate(0.5);
        for (var entity : level.getEntities((Entity) null, bounds)) {
            double strength = 0.1;
            if (falloff) {
                float distance = (float) Math.sqrt(entity.distanceToSqr(x, y, z));
                strength *= 1.5 * (1 - distance / 10D / 2D);
            }
            if (suction) strength = -strength;
            entity.setDeltaMovement(
                    entity.getDeltaMovement()
                            .add(
                                    direction.getStepX() * strength,
                                    direction.getStepY() * strength,
                                    direction.getStepZ() * strength));
        }
    }

