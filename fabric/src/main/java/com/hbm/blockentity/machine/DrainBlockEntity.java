    @Override
    public void tickServer() {
        networkPackNT(50);
        int fill = tank.getFill();
        if (fill == 0) return;
        var fluid = tank.getTankType();
        if (NTMFluidProperties.hasTrait(fluid, FluidTraitSimple.FT_Amat.class)) {
            level.explode(
                    null,
                    null,
                    null,
                    Vec3.atCenterOf(worldPosition),
                    10F,
                    true,
                    Level.ExplosionInteraction.BLOCK);
            return;
        }
        int released = Math.max(fill / 2, 1);
        tank.setFill(fill - released);
        setChanged();
        FluidReleaseType.SPILL.dispatch(level, worldPosition, fluid, tank, released);
        Environment.releaseGas((ServerLevel) level, fluid, released);
        if (released >= 100
                && level.getRandom().nextInt(20) == 0
                && NTMFluidProperties.hasTrait(fluid, FluidTraitSimple.FT_Liquid.class)
                && NTMFluidProperties.hasTrait(fluid, FluidTraitSimple.FT_Viscous.class)
                && NTMFluidProperties.hasTrait(fluid, FlammableTrait.class)) {
            placePuddle();
        }
    }

    private void placePuddle() {
        var facing = getBlockState().getValue(MultiblockCoreBlock.FACING);
        var start =
                Vec3.atCenterOf(worldPosition)
                        .add(-3D * facing.getStepX(), 0D, -3D * facing.getStepZ());
        double x = level.getRandom().nextGaussian() * 5D;
        double z = level.getRandom().nextGaussian() * 5D;
        var end = start.add(x, -25D, z);
        var hit =
                level.clip(
                        new ClipContext(
                                start,
                                end,
                                ClipContext.Block.COLLIDER,
                                ClipContext.Fluid.NONE,
                                CollisionContext.empty()));
        if (hit.getType() != HitResult.Type.BLOCK || hit.getDirection() != Direction.UP) return;
        var target = hit.getBlockPos().above();
        var state = level.getBlockState(target);
        var spill = ModBlocks.OIL_SPILL.get().defaultBlockState();
        if (!state.liquid() && state.canBeReplaced() && spill.canSurvive(level, target)) {
            level.setBlock(target, spill, Block.UPDATE_ALL);
        }
    }

    @Override
    public void tickClient() {
        if (tank.getFill() == 0) return;
        var player = Minecraft.getInstance().player;
        if (player == null
                || player.distanceToSqr(
                                worldPosition.getX(), worldPosition.getY(), worldPosition.getZ())
                        >= 10_000D) return;
        var facing = getBlockState().getValue(MultiblockCoreBlock.FACING);
        double x = worldPosition.getX() + 0.5D - 2.5D * facing.getStepX();
        double y = worldPosition.getY() + 0.5D;
        double z = worldPosition.getZ() + 0.5D - 2.5D * facing.getStepZ();
        var fluid = tank.getTankType();
        var property = NTMFluidProperties.get(fluid);
        int color = property == null ? CoolingTowerParticleOptions.NO_TINT : property.color();
        var client = (ClientLevel) level;
        if (NTMFluidProperties.hasTrait(fluid, FluidTraitSimple.FT_Gaseous.class)
                || Environment.particlePressure(level) < 0.08D) {
            var particle =
                    new CoolingTowerParticleOptions(
                            0.375F,
                            3F,
                            0.5F,
                            100 + level.getRandom().nextInt(50),
                            0.075F,
                            true,
                            0.25F,
                            color);
            client.addParticle(particle, true, false, x, y, z, 0D, 0D, 0D);
        } else {
            client.addParticle(new SplashParticleOptions(color), true, false, x, y, z, 0D, 0D, 0D);
        }
    }

