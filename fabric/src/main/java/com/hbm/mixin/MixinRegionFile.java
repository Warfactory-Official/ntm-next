package com.hbm.mixin;

import com.hbm.explosion.FalloutJournal;
import com.llamalad7.mixinextras.injector.wrapmethod.WrapMethod;
import com.llamalad7.mixinextras.injector.wrapoperation.Operation;
import java.io.IOException;
import java.nio.ByteBuffer;
import net.minecraft.world.level.ChunkPos;
import net.minecraft.world.level.chunk.storage.RegionFile;
import net.minecraft.world.level.chunk.storage.RegionStorageInfo;
import org.spongepowered.asm.mixin.Final;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.Shadow;

@Mixin(RegionFile.class)
public abstract class MixinRegionFile {
    @Shadow @Final private RegionStorageInfo info;

    @WrapMethod(method = "write")
    private void hbm$acknowledgeFalloutBiomes(
            ChunkPos pos, ByteBuffer data, Operation<Void> original) throws IOException {
        ByteBuffer written = data.asReadOnlyBuffer();
        original.call(pos, data);
        FalloutJournal.written(info, pos, written);
    }
}
