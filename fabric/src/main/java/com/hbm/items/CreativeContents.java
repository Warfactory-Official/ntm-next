    private static ItemStack identifier(Fluid fluid) {
        ItemStack stack = new ItemStack(ModItems.FLUID_IDENTIFIER);
        stack.set(
                ModDataComponents.FLUID_IDENTIFIER.get(),
                FluidIdentifierData.EMPTY.withPrimary(fluid));
        return stack;
    }

    private static void acceptDisperser(Consumer<ItemStack> out, ItemDisperser item) {
        for (Fluid fluid : NTMFluids.displayOrder()) {
            if (!item.isCreativeVariant(fluid)) continue;
            out.accept(item.make(fluid, item.capacity));
        }
    }

    private static void acceptPerFluid(
            Consumer<ItemStack> out, Function<Fluid, ItemStack> factory) {
        for (Fluid fluid : NTMFluids.displayOrder()) {
            if (NTMFluidProperties.hasTrait(fluid, FT_NoID.class)) continue;
            out.accept(factory.apply(fluid));
        }
    }

    private static void acceptContainerFamily(Consumer<ItemStack> out, ItemFluidTank item) {
        out.accept(new ItemStack(item));
        for (Fluid fluid : NTMFluids.displayOrder()) {
            if (!item.canStore(fluid)) continue;
            if (item != ModItems.FLUID_TANK_LEAD.get()
                    && NTMFluidProperties.hasTrait(fluid, FT_LeadContainer.class)) {
                continue;
            }
            out.accept(item.make(fluid, item.capacity));
        }
    }

