package com.hbm.blocks.bomb;

import com.hbm.blocks.SectionGeometryProvider;
import net.minecraft.core.BlockPos;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.util.RandomSource;
import net.minecraft.world.level.BlockGetter;
import net.minecraft.world.level.Level;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.Blocks;
import net.minecraft.world.level.block.state.BlockBehaviour;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.level.block.state.StateDefinition;
import net.minecraft.world.level.block.state.properties.IntegerProperty;
import net.minecraft.world.phys.shapes.CollisionContext;
import net.minecraft.world.phys.shapes.Shapes;
import net.minecraft.world.phys.shapes.VoxelShape;

public class DigammaMatterBlock extends Block implements SectionGeometryProvider {

    @Override
    public boolean ownsBoundaryFaceAdmission() {
        return true;
    }

    public static final IntegerProperty AGE = IntegerProperty.create("age", 0, 7);

    public DigammaMatterBlock(BlockBehaviour.Properties properties) {
        super(properties);
        registerDefaultState(stateDefinition.any().setValue(AGE, 0));
    }

    @Override
    protected void createBlockStateDefinition(StateDefinition.Builder<Block, BlockState> builder) {
        builder.add(AGE);
    }

    @Override
    protected VoxelShape getShape(
            BlockState state, BlockGetter level, BlockPos pos, CollisionContext context) {
        return DigammaBounds.shape(DigammaBounds.sample());
    }

    @Override
    protected VoxelShape getCollisionShape(
            BlockState state, BlockGetter level, BlockPos pos, CollisionContext context) {
        return Shapes.empty();
    }

    @Override
    protected void onPlace(
            BlockState state,
            Level level,
            BlockPos pos,
            BlockState oldState,
            boolean movedByPiston) {
        if (!level.isClientSide()) {
            level.scheduleTick(pos, this, 10 + level.getRandom().nextInt(40));
        }
    }

    @Override
    protected void tick(BlockState state, ServerLevel level, BlockPos pos, RandomSource random) {
        var age = state.getValue(AGE);
        level.setBlock(pos, Blocks.AIR.defaultBlockState(), Block.UPDATE_ALL);
        if (age == 7) {
            return;
        }

        var successor = defaultBlockState().setValue(AGE, age + 1);
        var target = new BlockPos.MutableBlockPos();
        for (int x = -1; x <= 1; x++) {
            for (int y = -1; y <= 1; y++) {
                for (int z = -1; z <= 1; z++) {
                    var distance = Math.abs(x) + Math.abs(y) + Math.abs(z);
                    if (distance == 0 || distance > 2) {
                        continue;
                    }
                    target.setWithOffset(pos, x, y, z);
                    if (!level.getBlockState(target).is(this)) {
                        level.setBlock(target, successor, Block.UPDATE_ALL);
                    }
                }
            }
        }
    }
}
