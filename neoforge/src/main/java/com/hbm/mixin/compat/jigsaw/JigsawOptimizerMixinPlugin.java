package com.hbm.mixin.compat.jigsaw;

import java.util.List;
import java.util.Set;
import org.objectweb.asm.tree.ClassNode;
import org.spongepowered.asm.mixin.extensibility.IMixinConfigPlugin;
import org.spongepowered.asm.mixin.extensibility.IMixinInfo;

public final class JigsawOptimizerMixinPlugin implements IMixinConfigPlugin {
    private static final boolean SLO =
            JigsawOptimizerMixinPlugin.class
                            .getClassLoader()
                            .getResource(
                                    "telepathicgrunt/structure_layout_optimizer/StructureLayoutOptimizerMod.class")
                    != null;

    @Override
    public boolean shouldApplyMixin(String target, String mixin) {
        return !SLO;
    }

    @Override
    public void onLoad(String mixinPackage) {}

    @Override
    public String getRefMapperConfig() {
        return null;
    }

    @Override
    public void acceptTargets(Set<String> mine, Set<String> other) {}

    @Override
    public List<String> getMixins() {
        return null;
    }

    @Override
    public void preApply(String name, ClassNode node, String mixin, IMixinInfo info) {}

    @Override
    public void postApply(String name, ClassNode node, String mixin, IMixinInfo info) {}
}
