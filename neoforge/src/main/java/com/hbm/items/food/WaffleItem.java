package com.hbm.items.food;

import com.hbm.explosion.MiniNukeExplosion;
import net.minecraft.world.entity.LivingEntity;
import net.minecraft.world.item.Item;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.level.Level;

public class WaffleItem extends Item {

    public WaffleItem(Properties props) {
        super(props);
    }

    @Override
    public ItemStack finishUsingItem(ItemStack stack, Level level, LivingEntity entity) {
        ItemStack rest = super.finishUsingItem(stack, level, entity);
        if (!level.isClientSide()) {
            MiniNukeExplosion.MEDIUM.detonate(
                    level, entity.getX(), entity.getY() + 0.5D, entity.getZ());
        }
        return rest;
    }
}
